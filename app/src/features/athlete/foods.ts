/** Local date key, YYYY-MM-DD. */
export const dateKey = (d: Date) =>
  `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
export const shiftDate = (key: string, days: number) => {
  const [y, m, d] = key.split("-").map(Number);
  return dateKey(new Date(y, m - 1, d + days));
};
export const dateLabel = (key: string, today: string) => {
  if (key === today) return "Today";
  if (key === shiftDate(today, -1)) return "Yesterday";
  const [y, m, d] = key.split("-").map(Number);
  return new Date(y, m - 1, d).toLocaleDateString("en-IN", {
    weekday: "short",
    day: "numeric",
    month: "short",
  });
};

/** A plan meal's foods: exact items with portions (F5-12). */
export type PlanItem = {
  foodId: string;
  qty: number;
  unit: string;
  cooked?: "home" | "restaurant";
};

export function planItemMacros(i: PlanItem, mine: Food[] = []) {
  const f = findFood(i.foodId, mine);
  if (!f) return { kcal: 0, p: 0, c: 0, f: 0 };
  const u = unitsOf(f).find((x) => x.key === i.unit) ?? f.units[0] ?? GRAMS;
  return macrosFor(f, u.grams * i.qty, i.cooked);
}

export function planItemText(i: PlanItem, mine: Food[] = []) {
  const f = findFood(i.foodId, mine);
  if (!f) return "";
  const u = unitsOf(f).find((x) => x.key === i.unit) ?? GRAMS;
  return `${f.name} ${portionText(u.key === "g" ? u.grams * i.qty : i.qty, u.label)}`;
}

/** Turn a plan item into a log entry for one day. */
export function logFromItem(
  i: PlanItem,
  date: string,
  meal: MealSlot,
  id: string,
  mine: Food[] = [],
): FoodLog | null {
  const f = findFood(i.foodId, mine);
  if (!f) return null;
  const u = unitsOf(f).find((x) => x.key === i.unit) ?? f.units[0] ?? GRAMS;
  const grams = u.grams * i.qty;
  return {
    id,
    date,
    meal,
    foodId: f.id,
    name: f.name,
    qty: u.key === "g" ? grams : i.qty,
    unit: u.label,
    grams,
    cooked: f.oil ? (i.cooked ?? "home") : undefined,
    source: f.source,
    macros: macrosFor(f, grams, i.cooked),
  };
}

/** Which day slot a plan meal belongs to, from its name or time. */
export function slotForMeal(name: string, time: string): MealSlot {
  const n = name.toLowerCase();
  if (n.includes("breakfast")) return "breakfast";
  if (n.includes("lunch")) return "lunch";
  if (n.includes("dinner") || n.includes("supper")) return "dinner";
  if (n.includes("snack") || n.includes("evening") || n.includes("mid"))
    return "snacks";
  const m = time.match(/(\d+)(?::\d+)?\s*(am|pm)/i);
  if (!m) return "snacks";
  const h = (Number(m[1]) % 12) + (m[2].toLowerCase() === "pm" ? 12 : 0);
  return slotForHour(h);
}
