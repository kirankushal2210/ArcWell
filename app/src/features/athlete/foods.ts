// Food data for logging (F5): Indian dishes and basic foods with Indian portions (katori, roti,
// piece, glass), each shown with its gram weight. Values are per 100 g, home-style.
// SAMPLE DATA: values are estimates. The real data is IFCT 2017 plus Arcwell-reviewed dishes, with
// standard portion weights checked by a nutrition reviewer (PLAN.md pre-launch tasks); no crowd data (D45).

export type Macros = { kcal: number; p: number; c: number; f: number };
export type Unit = { key: string; label: string; grams: number };
export type FoodSource = "verified" | "ifct" | "mine";

export type Food = {
  id: string;
  name: string;
  /** Other names people search for: Hindi names and common spellings ("dahi" finds curd). */
  aliases: string[];
  source: FoodSource;
  /** Dishes (how people eat) list before raw ingredients. */
  kind: "dish" | "ingredient";
  per100: Macros;
  /** First unit is the default; grams are always offered as well. */
  units: Unit[];
  /** Cooked with oil, so home-style or restaurant changes the numbers (F5-06). */
  oil: boolean;
};

export type MealSlot = "breakfast" | "lunch" | "snacks" | "dinner";
export const MEAL_SLOTS: { value: MealSlot; label: string }[] = [
  { value: "breakfast", label: "Breakfast" },
  { value: "lunch", label: "Lunch" },
  { value: "snacks", label: "Snacks" },
  { value: "dinner", label: "Dinner" },
];
export const slotLabel = (s: MealSlot) =>
  MEAL_SLOTS.find((m) => m.value === s)?.label ?? "Snacks";

/** The meal people are most likely logging now (F5-03, F5-04). */
export function slotForHour(h: number): MealSlot {
  if (h < 11) return "breakfast";
  if (h < 16) return "lunch";
  if (h < 19) return "snacks";
  return "dinner";
}

/** A logged food (F5-01). Numbers are stored, so later data changes never rewrite history. */
export type FoodLog = {
  id: string;
  /** Local date, YYYY-MM-DD. */
  date: string;
  meal: MealSlot;
  foodId?: string;
  name: string;
  /** Portion as logged, e.g. 1.5 of "katori". */
  qty: number;
  unit: string;
  grams: number;
  cooked?: "home" | "restaurant";
  source: FoodSource | "quick";
  macros: Macros;
  /** The plate photo, when logged with a scan (D94). */
  photoUri?: string;
  /** Logged from the meal plan with "Ate this" (F5-12). */
  fromPlan?: string;
  /** Logged with "Ate something else" instead of this plan meal: the coach sees the swap. */
  swappedFor?: string;
};

